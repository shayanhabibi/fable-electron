    let echoStatus = stage "status" {
        consumes Inputs.initialGitStatus (fun status ->
            $"
Summary of current status for GitNet:

Electron Cached Version: {status.delta.Versions.CachedElectron.ToString()}
    The electron release recorded in ci/cache.json.

Is Probably Pulled: {ElectronDelta.isProbablyPulled status.delta}
    The cached electron version is ahead of the project file's, so this
    branch was merged from a generated pull.

Current Electron Version: {status.delta.Versions.FableElectronElectron.ToString()}
    The project file electron version. Updated only when merged to main.

Current Package Version: {status.delta.Versions.FableElectronPackage.ToString()}
    The package version of Fable.Electron.

Downloaded Version: {status.delta.Versions.DownloadedElectron.ToString()}
    The version of Electron downloaded in this run.

Delta: {ElectronDelta.deltaKind status.delta}
    A major delta submits a pull instead of publishing.

Next version: {ElectronDelta.nextElectronVersion status.delta |> _.ToString()}

Is Electron Package Updated: {ElectronDelta.isBump status.delta}
    Whether the Electron package changed, from the electron version or the generator.

Is Any Package Updated: {status.anyPackageUpdated}

Next versions:
    Remoting: {status.remoting}
    Forge: {status.forge}

Package Requires Pull: {status.requiresPull}
