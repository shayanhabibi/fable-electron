//%ReleaseStage%START%
    /// <summary>
    /// The versioning, commit, tag, publish and pull request steps of a scheduled generation, decided from
    /// the status the run calculated before it began.
    /// </summary>
    /// <remarks>
    /// When any package changed, a major electron delta lands on a branch and opens a pull request into
    /// <c>develop</c>; any other delta commits, tags and publishes on the current branch. Failures recorded in
    /// <paramref name="generationFailures"/> put the run on a branch and into the pull request body.
    /// <c>--dry-run</c> prints each git, nuget and github action instead of performing it.
    /// </remarks>
    let release (generationFailures: ResizeArray<string>) = input {
        let! dryRun = Options.dryRun
        and! pack = pack
        and! publish = publish
        let status = DependencySpec.map2 (fun status release -> status, release) Inputs.initialGitStatus (DependencySpec.require Inputs.release)
        let requiresPull (status: {| delta: ElectronDelta; forge: {| version: GitNetTag voption; bump: SepochSemver voption |}; remoting: {| version: GitNetTag voption; bump: SepochSemver voption |}; anyPackageUpdated: bool; requiresPull: bool |}) =
            status.requiresPull || generationFailures.Count > 0
        let git (arguments: string) = Cmd.create "git" arguments
        // Performs the action, or prints it under --dry-run.
        let act (description: string) (perform: unit -> unit) =
            if dryRun then printfn $"[ACTION] {description}" else perform ()
        // Runs the command, or prints it under --dry-run.
        let actCmd (command: Cmd) =
            if dryRun then Operation.ofAsync (async { printfn $"[ACTION] {Cmd.toLogString command}" }) else execute command
        // Packages publish when a package changed and the run stays on its branch.
        let publishable (stage: Partas.Build.Internal.StageContext) =
            match status.Read (StageContext.publishedValues stage) with
            | Ok(status, _) -> status.anyPackageUpdated && not (requiresPull status)
            | Error _ -> false
        let publishPackages =
            stage "publish packages" {
                consumes status (fun _ -> Operation.ret ())
                pack
                publish
            }
            |> StageContext.addPredicateBecause (ValueSome "the run opens a pull request or changes nothing") publishable
        return stage "release" {
            stage "version and commit" {
                consumes status (fun (status, requested) ->
                    match status.anyPackageUpdated, requested with
                    | false, _ -> Operation.ofAsync (async { printfn "No changes during CI." })
                    | true, None -> Operation.fail (FailureCause.Reported "A package changed, but no release was requested or found.")
                    | true, Some release ->
                        let branch = Release.branchFor release
                        let guardBranch =
                            if requiresPull status then
                                executeCapture (git $"ls-remote --heads origin {branch}")
                                |> Operation.bind (fun result ->
                                    if not (String.IsNullOrWhiteSpace result.Stdout) && not dryRun then
                                        Operation.fail (FailureCause.Reported $"A pull already exists for release {release.tagName}.")
                                    else actCmd (git $"checkout -b {branch}"))
                            else Operation.ret ()
                        guardBranch
                        |> Operation.bind (fun () ->
                            Operation.ofAsync (async {
                                let deltaKind = ElectronDelta.deltaKind status.delta
                                let versions = [
                                    Release.electron, ElectronDelta.nextElectronVersion status.delta
                                    match status.forge.bump with
                                    | ValueSome bump -> Release.forge, bump
                                    | ValueNone -> ()
                                    match status.remoting.bump with
                                    | ValueSome bump -> Release.remoting, bump
                                    | ValueNone -> ()
                                ]
                                let commitMessage = Versions.makeCommitMessage $"Electron binding update to match {release.tagName}" deltaKind
                                let runtime = GitNet.createRuntime ()
                                match status.delta.Versions.DownloadedElectron with
                                | ValueSome downloaded ->
                                    act $"Set Fable.Electron ElectronVersion: {downloaded}" (fun () ->
                                        Release.writeProjectProperty Release.electron "ElectronVersion" (downloaded.ToString()))
                                | ValueNone -> ()
                                for project, version in versions do
                                    act $"Set {project.Name} Version: {version.SemVer}" (fun () ->
                                        Release.writeProjectProperty project "Version" (version.SemVer.ToString())
                                        Release.writeProjectProperty project "PackageVersion" (version.SemVer.ToString()))
                                act $"Write to cache: {release}" (fun () ->
                                    File.WriteAllText(Repo.VirtualFileSystem.ci.``cache.json``.FullName, JsonSerializer.Serialize release))
                                let files = Release.generatedFiles ()
                                act $"Stage files: %A{files}" (fun () -> runtime.StageFiles files)
                                act $"Commit with message: {commitMessage}" (fun () -> runtime.CommitChanges(message = commitMessage, appendCommit = false))
                                if not (requiresPull status) then
                                    let tags = versions |> List.map snd
                                    act $"Git tag with: %A{tags |> List.map _.ToString()}" (fun () -> runtime.CommitTags tags)
                                act "Generate release notes, stage and commit" (fun () ->
                                    runtime.DryRun().Markdown |> runtime.WriteToOutputAndStage
                                    runtime.CommitChanges(appendCommit = false))
                            }))
                )
            }
            publishPackages
            stage "push" {
                consumes status (fun (status, requested) ->
                    match requested with
                    | Some release when status.anyPackageUpdated ->
                        executeCapture (git "rev-parse --abbrev-ref HEAD")
                        |> Operation.map _.Stdout.Trim()
                        |> Operation.bind (fun branch ->
                            actCmd (git $"push -u origin {branch}")
                            |> Operation.bind (fun () -> actCmd (git "push --tags origin"))
                            |> Operation.bind (fun () ->
                                if not (requiresPull status) then Operation.ret () else
                                let title, body = Release.pullRequestText release (List.ofSeq generationFailures)
                                let info = Release.pullRequestInfo ()
                                if dryRun then Operation.ofAsync (async { printfn $"[ACTION] Send pull to develop:\n{title}\n\n{body}" }) else
                                Repository.createPr (fun args -> {
                                    args with
                                        Reviewer = List.ofArray info.reviewers
                                        Label = List.ofArray info.labels
                                        Project = List.ofArray info.projects
                                        Assignee = List.ofArray info.assignees
                                        Base = Some "develop"
                                        Head = Some branch
                                        Title = Some title
                                        Body = Some body
                                })))
                    | _ -> Operation.ret ()
                )
            }
        }
    }
//%ReleaseStage%END%

//%GenerationFailures%START%
/// Records the failures of the generation stages ahead of the release, so the pull request can carry them.
let private generationFailures = ResizeArray<string>()
let private recordFailure (context: FailureContext) =
    let nested = context.Nested |> List.collect (fun report -> ScopeReport.failures report |> List.map (fun failure -> report.Name, failure))
    let own = context.Failures |> List.map (fun failure -> context.Scope, failure)
    for scope, failure in own @ nested do
        generationFailures.Add $"{scope}: {FailureCause.describe failure.Cause}"
//%GenerationFailures%END%

