module Inputs =
    /// Reads and returns the cached release info
    let cache =
        Operation.ofAsync (async {
            if Repo.VirtualFileSystem.ci.``cache.json``.Exists |> not then return None else
            return
                File.ReadAllText Repo.VirtualFileSystem.ci.``cache.json``.FullName
                |> JsonSerializer.Deserialize<ReleaseInfo>
                |> Some
        })
        |> Producer.emptyDefine "fetch cache"
//%ReleaseProducer%START%
    /// asynchronously retrieves the release info for either the requested release/bump type
    /// from the electron repo using the gh cli. consider this to be the requested release info
    /// we are generating against. Falls back to the 'latest' release if none are specifically
    /// requested.
    let release =
        Producer.define
            "release"
            (input {
                let! release = Options.release
                and! patchOnly = Options.patchOnly
                and! minorOnly = Options.minorOnly
                and! cacheRelease = Options.cache
                return {| release = release; patchOnly = patchOnly; minorOnly = minorOnly; cacheRelease = cacheRelease |}
            })
            (DependencySpec.zip cache Electron.getReleases)
            (fun inputs (cache, releases) ->
                let cache = cache |> Option.map (_.tagName.Trim('v') >> Semver.SemVersion.Parse)
                if (inputs.patchOnly || inputs.minorOnly) && cache.IsNone then
                    failwith "--only-minor && --only-patch can only be used when there is a cached release value. \
                            Either specify a release to operate on with --release or allow the latest release to download"
                elif inputs.cacheRelease && cache.IsNone then
                    failwith "--cache-release can only be used when there is a cached release object @ /ci/cache.json"
                else
                Operation.ofAsync (async {
                return releases
                |> List.filter (_.isPrerelease >> not)
                |> List.filter (fun info ->
                    let value = Semver.SemVersion.Parse(info.tagName.Trim('v'))
                    match inputs.release, cache with
                    | Some requested, _ -> value = requested
                    | None, Some cached when inputs.cacheRelease -> value = cached
                    | None, Some cached when inputs.minorOnly && inputs.patchOnly ->
                        value.Major = cached.Major
                        && (value.Minor > cached.Minor || (value.Minor = cached.Minor && value.Patch > cached.Patch))
                    | None, Some cached when inputs.patchOnly ->
                        value.Major = cached.Major && value.Minor = cached.Minor && value.Patch > cached.Patch
                    | None, Some cached when inputs.minorOnly ->
                        value.Major = cached.Major && value.Minor > cached.Minor
                    | _ -> info.isLatest
                )
                |> function
                    | [] when inputs.release.IsSome ->
                        failwith $"Unable to find the specified release {inputs.release.Value}"
                    | [] -> None
                    | values -> List.maxBy _.createdAt values |> Some
                })
            )
//%ReleaseProducer%END%
    /// Asynchronously downloads the electron api file for the requested release
    let downloadApi =
        Producer.define
            "download api"
            InputSpec.empty
            (DependencySpec.require release)
            (fun () -> function
                | Some release ->
                    Electron.downloadElectronApi
                        true
                        Repo.VirtualFileSystem.temp.``electron-api.json``.FullName
                        release
                | None -> Operation.ret ()
            )

    /// Asynchronously calculates the electron delta versions using the
    /// requested release, cache, and project values
    let electronDeltaVersions =
        DependencySpec.zip cache release
        |> DependencySpec.map (fun (cache,release) ->
            {
                FableElectronPackage =
                    match Repo.Project.``Fable.Electron``.Version with
                    | "" -> ValueNone
                    | version -> Semver.SemVersion.Parse version |> ValueSome
                FableElectronElectron =
                    match Repo.Project.``Fable.Electron``.Property("ElectronVersion") with
                    | "" -> ValueNone
                    | version -> Semver.SemVersion.Parse version |> ValueSome
                CachedElectron =
                    cache
                    |> Option.map (
                        _.tagName.Trim('v')
                        >> Semver.SemVersion.Parse
                        )
                    |> Option.toValueOption
                DownloadedElectron =
                    release
                    |> Option.map (
                        _.tagName.Trim('v')
                        >> Semver.SemVersion.Parse
                        )
                    |> Option.toValueOption
            }
        )

    /// Checks whether the generated file is modified using git
    let electronIsDirty() =
        let fileIsDirty file =
            Repo.Git.Run($"status -s -- {file}")
            |> function
                | "" -> false
                | v -> true
        Repo.Git.IsDirty()
        && fileIsDirty Repo.FileSystem.src.``Fable.Electron``.``Program.fs``
    /// calculated electron delta versions at request time
    let electronDelta =
        electronDeltaVersions
        |> DependencySpec.map  (fun deltaVersions ->
            let defaultInt = ValueOption.defaultValue 0
            let deltaPath (path: Semver.SemVersion -> bigint) =
                (deltaVersions.DownloadedElectron
                |> ValueOption.map (path >> int)
                |> defaultInt) - (
                deltaVersions.FableElectronElectron
                |> ValueOption.map (path >> int)
                |> defaultInt
                )
            {
                Versions = deltaVersions
                Dirty = electronIsDirty()
                Major = deltaPath _.Major
                Minor = deltaPath _.Minor
                Patch = deltaPath _.Patch
            }
        )

    let initialGitStatus =
        (electronDelta, GitNet.initSpecs)
        ||> DependencySpec.map2 (fun electronDelta specs ->
            let forge, remoting = specs.forge, specs.remoting
            let anyPackageUpdated =
                forge.bump.IsSome
                || remoting.bump.IsSome
                || ElectronDelta.isBump electronDelta
            let requiresPull =
                not (ElectronDelta.isProbablyPulled electronDelta)
                && (ElectronDelta.deltaKind electronDelta).IsMajor
            {| delta = electronDelta; forge = forge; remoting = remoting; anyPackageUpdated = anyPackageUpdated; requiresPull = requiresPull  |}
        )

/// The versioning, commit, tag and pull request flow at the end of a scheduled generation.
module Release =
    [<CLIMutable>]
    type PullRequestInfo = {
        reviewers: string array
        labels: string array
        projects: string array
        assignees: string array
    }
    /// The reviewers, labels, projects and assignees a generated pull request carries, from <c>ci/pull_request.json</c>.
    let pullRequestInfo () =
        try
            Repo.FileSystem.ci.``pull_request.json``.FullName
            |> File.ReadAllText
            |> JsonSerializer.Deserialize<PullRequestInfo>
        with _ -> { reviewers = [||]; labels = [||]; projects = [||]; assignees = [||] }
    /// Sets one MSBuild property in the first property group of the project file.
    let writeProjectProperty (project: ProjectRef) (name: string) (value: string) =
        let document = System.Xml.Linq.XDocument.Load(project.Path, System.Xml.Linq.LoadOptions.PreserveWhitespace)
        let group = document.Root.Elements(System.Xml.Linq.XName.Get "PropertyGroup") |> Seq.head
        Baked.IO.writeProperty group name (fun _ -> value) |> ignore
        Baked.IO.save project.Path document
    let private project name = Projects.srcProjects |> List.find _.Name.Equals(name: string)
    let electron = project "Fable.Electron"
    let forge = project "Fable.Electron.Forge"
    let remoting = project "Fable.Electron.Remoting"
    /// The branch a generation of the given release lands on when it requires a pull request.
    let branchFor (release: ReleaseInfo) = $"ci/electron/{release.tagName}"
    /// The files the generation touches, relative to the repository root: the packable projects, their
    /// compiled sources, and the cache.
    let generatedFiles () =
        let root = Repo.FileSystem.``.``.FullName
        let compiledFiles (project: ProjectRef) =
            let document = System.Xml.Linq.XDocument.Load project.Path
            document.Descendants(System.Xml.Linq.XName.Get "Compile")
            |> Seq.choose (fun element -> element.Attribute(System.Xml.Linq.XName.Get "Include") |> Option.ofObj)
            |> Seq.map (fun attribute -> Path.Combine(project.Directory, attribute.Value))
            |> Seq.filter File.Exists
            |> List.ofSeq
        [ electron; forge; remoting ]
        |> List.collect (fun project -> project.Path :: compiledFiles project)
        |> List.append [ Repo.VirtualFileSystem.ci.``cache.json``.FullName ]
        |> List.map (fun path -> Path.GetRelativePath(root, path).Replace('\\', '/'))
    /// The title and body of the pull request for a generated release, with the generation failures when
    /// there were any.
    let pullRequestText (release: ReleaseInfo) (failures: string list) =
        match failures with
        | [] ->
            $"Electron {release.tagName}",
            $"""Bindings for electron {release.tagName} were generated successfully and passed tests.

This electron release was created on {release.createdAt}.

Once this pull is merged into `main`, publishing will occur. It is recommended to merge into `develop` for major electron versions first.
"""
        | failures ->
            let details =
                failures
                |> List.map (fun failure -> $"<details>\n<summary>Error</summary>\n\n```\n{failure}\n```\n\n</details>")
                |> String.concat "\n"
            $"[GEN ERROR] For Electron {release.tagName}",
            $"""During the build process, I came across some errors. Once corrected, please consider merging into `develop`.

{details}"""

